create table if not exists public.user_profiles (
  id uuid primary key default gen_random_uuid(),
  username text not null unique,
  full_name text not null,
  email text,
  password_hash text not null,
  role text not null default 'student' check (role in ('student', 'teacher', 'admin')),
  cash_balance bigint not null default 0 check (cash_balance >= 0),
  coin_balance bigint not null default 0 check (coin_balance >= 0),
  is_blocked boolean not null default false,
  created_at timestamptz not null default now()
);

create unique index if not exists user_profiles_email_lower_idx
  on public.user_profiles (lower(email))
  where email is not null;

create table if not exists public.user_sessions (
  session_hash text primary key,
  user_id uuid not null references public.user_profiles(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists user_sessions_expiry_idx
  on public.user_sessions (expires_at);

create table if not exists public.coin_settings (
  id boolean primary key default true check (id),
  cash_per_coin bigint not null default 5 check (cash_per_coin > 0),
  attendance_cash bigint not null default 0 check (attendance_cash >= 0),
  attendance_coins bigint not null default 0 check (attendance_coins >= 0),
  auto_attendance_reward boolean not null default false,
  updated_at timestamptz not null default now()
);

insert into public.coin_settings (id) values (true)
on conflict (id) do nothing;

create table if not exists public.coin_rewards (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  cost_coins bigint not null check (cost_coins > 0),
  icon text not null default 'bi-gift',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.reward_orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.user_profiles(id) on delete cascade,
  reward_id bigint not null references public.coin_rewards(id),
  coins_spent bigint not null check (coins_spent > 0),
  status text not null default 'pending' check (status in ('pending', 'delivered', 'cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.study_groups (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  description text not null default '',
  created_by uuid not null references public.user_profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.group_members (
  group_id uuid not null references public.study_groups(id) on delete cascade,
  user_id uuid not null references public.user_profiles(id) on delete cascade,
  added_at timestamptz not null default now(),
  primary key (group_id, user_id)
);

create table if not exists public.group_schedules (
  id uuid primary key default gen_random_uuid(),
  group_id uuid not null references public.study_groups(id) on delete cascade,
  subject text not null,
  day_of_week smallint not null check (day_of_week between 0 and 6),
  start_time time not null,
  time_zone text not null default 'Asia/Tashkent',
  interval_days smallint not null default 7 check (interval_days in (1, 2, 7, 14)),
  anchor_date date not null,
  created_at timestamptz not null default now()
);

create table if not exists public.group_sessions (
  id uuid primary key default gen_random_uuid(),
  group_id uuid not null references public.study_groups(id) on delete cascade,
  schedule_id uuid references public.group_schedules(id) on delete set null,
  subject text not null,
  starts_at timestamptz not null,
  status text not null default 'scheduled' check (status in ('scheduled', 'completed')),
  marked_by uuid references public.user_profiles(id),
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists group_sessions_group_start_idx
  on public.group_sessions (group_id, starts_at);
create unique index if not exists group_sessions_schedule_occurrence_idx
  on public.group_sessions (schedule_id, starts_at)
  where schedule_id is not null;

create table if not exists public.attendance (
  session_id uuid not null references public.group_sessions(id) on delete cascade,
  user_id uuid not null references public.user_profiles(id) on delete cascade,
  present boolean not null,
  marked_by uuid not null references public.user_profiles(id),
  marked_at timestamptz not null default now(),
  primary key (session_id, user_id)
);

create table if not exists public.wallet_transactions (
  id bigint generated always as identity primary key,
  user_id uuid not null references public.user_profiles(id) on delete cascade,
  cash_delta bigint not null default 0,
  coin_delta bigint not null default 0,
  description text not null,
  attendance_session_id uuid references public.group_sessions(id),
  created_at timestamptz not null default now(),
  check (cash_delta <> 0 or coin_delta <> 0)
);

create unique index if not exists wallet_transactions_attendance_once_idx
  on public.wallet_transactions (user_id, attendance_session_id)
  where attendance_session_id is not null;
